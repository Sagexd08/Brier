/**
 * Fetch a committed artifact.
 *
 * A missing or malformed artifact resolves to `missing` carrying the real
 * reason. It never resolves to a fabricated default — a UI that invents a
 * number when the file is absent is worse than one that shows nothing.
 */
export async function loadArtifact<T>(file: string, label: string): Promise<Load<T>> {
  try {
    const res = await fetch(`/artifacts/${file}`, { cache: 'no-store' });
    if (!res.ok) {
      return {
        state: 'missing',
        what: label,
        detail: `artifacts/${file} returned HTTP ${res.status}. Regenerate it by running the pipeline scripts in the repository root.`,
      };
    }
    return { state: 'ok', data: (await res.json()) as T };
  } catch (err) {
    return {
      state: 'missing',
      what: label,
      detail: `artifacts/${file} could not be read (${
        err instanceof Error ? err.message : 'unknown error'
      }). It is generated by the repo's pipeline and is not committed as a placeholder.`,
    };
  }
}

// ---------------------------------------------------------------------
// formatting — every helper preserves precision; none rounds for looks
// ---------------------------------------------------------------------

export const fmt = {
  /** Fixed decimals. Never trims significant digits to look tidier. */
  dec: (v: number, places = 4) => v.toFixed(places),
  /** Thousands separators for gas and byte counts. */
  int: (v: number) => v.toLocaleString('en-US'),
  pct: (v: number, places = 2) => `${v.toFixed(places)}%`,
  /** wei -> ETH, at full precision. */
  eth: (wei: number, places = 6) => (wei / 1e18).toFixed(places),
  seconds: (s: number, places = 2) => `${s.toFixed(places)} s`,
};

/** The label the project itself uses for a value it has not measured. */
export const NOT_MEASURED = 'not measured';

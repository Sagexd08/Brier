/**
 * Data access for the Brier UI.
 *
 * Two sources only, per the brief:
 *   1. committed JSON artifacts, served from /public/artifacts (copied
 *      unmodified from the repo's artifacts/ directory), and
 *   2. live chain reads over RPC.
 *
 * There is no database, no localStorage, and no mock data — including in
 * loading and error states. If an artifact is missing or an RPC call fails,
 * the caller receives an explicit failure it must render as such. Nothing here
 * ever substitutes a plausible-looking value for a real one.
 */

export type Load<T> =
  | { state: 'loading' }
  | { state: 'ok'; data: T }
  | { state: 'missing'; what: string; detail: string };

